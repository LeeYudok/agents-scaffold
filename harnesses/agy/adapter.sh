#!/usr/bin/env bash
# Google Antigravity (agy) 어댑터 — .agents/rules/*.md, .agents/agents/*.md, .agents/hooks.json 생성 (#63, #64, #65).
# bin/agents-scaffold.sh 에서 harnesses/common.sh 뒤에 source 된다.
# shellcheck disable=SC2154

AGY_RULE_MARK="Generated by agents-scaffold from .claude/rules/"

agy_glob() {
  case "$1" in
    '**/'*) printf '%s' "$1" ;;
    /*) printf '**%s' "$1" ;;
    */*) printf '**/%s' "$1" ;;
    *) printf '%s' "$1" ;;
  esac
}

emit_agy_rules() {
  local src dst name paths globs p
  [ -d "$TARGET/.claude/rules" ] || return 0
  mkdir -p "$TARGET/.agents/rules"
  # 원본이 사라진 생성물은 지운다(사용자가 만든 파일은 표시가 없으므로 건드리지 않는다)
  for dst in "$TARGET/.agents/rules/"*.md; do
    [ -f "$dst" ] || continue
    grep -qF "$AGY_RULE_MARK" "$dst" || continue
    [ -f "$TARGET/.claude/rules/$(basename "$dst")" ] || rm -f "$dst"
  done
  for src in "$TARGET/.claude/rules/"*.md; do
    [ -f "$src" ] || continue
    name="$(basename "$src")"
    [ "$name" = "README.md" ] && continue
    dst="$TARGET/.agents/rules/$name"
    if [ -f "$dst" ] && ! grep -qF "$AGY_RULE_MARK" "$dst"; then
      echo "Warning: .agents/rules/$name was not generated by agents-scaffold — left untouched." >&2
      continue
    fi
    paths="$(claude_rule_paths "$src")"
    globs=""
    while IFS= read -r p; do
      [ -n "$p" ] || continue
      globs="${globs:+$globs,}$(agy_glob "$p")"
    done <<<"$paths"
    {
      echo "---"
      if [ -n "$globs" ]; then
        echo "trigger: glob"
        echo "globs: \"$globs\""
      else
        echo "trigger: always_on"
      fi
      echo "---"
      echo "> $AGY_RULE_MARK$name (#63) — edit the source, not this file."
      echo
      claude_rule_body "$src"
    } > "$dst.tmp"
    mv "$dst.tmp" "$dst"
  done
  echo "== agy rules generated at .agents/rules from .claude/rules ==" >&2
}

emit_agy_agents() {
  local src dst stem name desc body dir="$TARGET/.agents/agents" ext="md"
  [ -d "$TARGET/.claude/agents" ] || return 0
  mkdir -p "$dir"
  for dst in "$dir/"*."$ext"; do
    [ -f "$dst" ] || continue
    grep -qF "$AGENT_MARK" "$dst" || continue
    stem="$(basename "$dst" ".$ext")"
    [ -f "$TARGET/.claude/agents/$stem.md" ] || rm -f "$dst"
  done
  for src in "$TARGET/.claude/agents/"*.md; do
    [ -f "$src" ] || continue
    stem="$(basename "$src" .md)"
    [ "$stem" = "README" ] && continue
    dst="$dir/$stem.$ext"
    if [ -f "$dst" ] && ! grep -qF "$AGENT_MARK" "$dst"; then
      echo "Warning: ${dst#"$TARGET/"} was not generated by agents-scaffold — left untouched." >&2
      continue
    fi
    name="$(claude_fm_value "$src" name)"
    desc="$(claude_fm_value "$src" description)"
    if [ -z "$name" ] || [ -z "$desc" ]; then
      echo "Warning: .claude/agents/$stem.md has no one-line name/description — not generated for agy." >&2
      rm -f "$dst"
      continue
    fi
    body="$(claude_rule_body "$src")"
    name="${name//\'/\'\'}"; desc="${desc//\'/\'\'}"
    {
      echo "---"
      echo "name: '$name'"
      echo "description: '$desc'"
      echo "---"
      echo "> $AGENT_MARK$stem.md (#64) — edit the source, not this file."
      printf '%s\n' "$body"
    } > "$dst.tmp"
    mv "$dst.tmp" "$dst"
  done
  echo "== agy subagents generated at ${dir#"$TARGET/"} from .claude/agents ==" >&2
}

harness_apply_agy() {
  emit_agy_rules
  emit_agy_agents
  emit_hooks agy
}
