#!/usr/bin/env bash
# Codex CLI 어댑터 — .codex/agents/*.toml 및 .codex/hooks.json 생성 (#64, #65).
# bin/agents-scaffold.sh 에서 harnesses/common.sh 뒤에 source 된다.
# shellcheck disable=SC2154

emit_codex_agents() {
  local src dst stem name desc body dir="$TARGET/.codex/agents" ext="toml"
  [ -d "$TARGET/.claude/agents" ] || return 0
  mkdir -p "$dir"
  for dst in "$dir/"*."$ext"; do
    [ -f "$dst" ] || continue
    grep -qF "$AGENT_MARK" "$dst" || continue
    stem="$(basename "$dst" ".$ext")"
    [ -f "$TARGET/.claude/agents/$stem.md" ] || rm -f "$dst"
  done
  for src in "$TARGET/.claude/agents/"*.md; do
    [ -f "$src" ] || continue
    stem="$(basename "$src" .md)"
    [ "$stem" = "README" ] && continue
    dst="$dir/$stem.$ext"
    if [ -f "$dst" ] && ! grep -qF "$AGENT_MARK" "$dst"; then
      echo "Warning: ${dst#"$TARGET/"} was not generated by agents-scaffold — left untouched." >&2
      continue
    fi
    name="$(claude_fm_value "$src" name)"
    desc="$(claude_fm_value "$src" description)"
    if [ -z "$name" ] || [ -z "$desc" ]; then
      echo "Warning: .claude/agents/$stem.md has no one-line name/description — not generated for codex." >&2
      rm -f "$dst"
      continue
    fi
    body="$(claude_rule_body "$src")"
    if printf '%s' "$body" | grep -qF "'''"; then
      echo "Warning: .claude/agents/$stem.md contains ''' — cannot embed in a TOML literal string, skipped for codex." >&2
      rm -f "$dst"
      continue
    fi
    name="${name//\\/\\\\}"; name="${name//\"/\\\"}"
    desc="${desc//\\/\\\\}"; desc="${desc//\"/\\\"}"
    {
      echo "# $AGENT_MARK$stem.md (#64) — edit the source, not this file."
      echo "name = \"$name\""
      echo "description = \"$desc\""
      echo "developer_instructions = '''"
      printf '%s\n' "$body"
      echo "'''"
    } > "$dst.tmp"
    mv "$dst.tmp" "$dst"
  done
  echo "== codex subagents generated at ${dir#"$TARGET/"} from .claude/agents ==" >&2
}

harness_apply_codex() {
  emit_codex_agents
  emit_hooks codex
}
