# 하네스 어댑터 공통 파서 및 훅 변환 헬퍼.
# bin/agents-scaffold.sh 에서 source 된다 ($TARGET 사용).
# shellcheck disable=SC2154

# shellcheck disable=SC2034
AGENT_MARK="Generated by agents-scaffold from .claude/agents/"

# frontmatter 의 paths: 항목을 한 줄에 하나씩 낸다. frontmatter 가 없으면 빈 출력.
#   블록 목록(- 항목)과 인라인 배열([a, b]) 모두, 따옴표 스칼라와 줄 끝 # 주석을 YAML 대로 처리한다
#   (따옴표 안의 # 는 값이다). CRLF 로 체크아웃된 파일(Windows autocrlf)도 같은 결과가 나오도록
#   줄 끝 \r 을 뗀다. awk 문자열의 \047 은 작은따옴표다.
claude_rule_paths() {
  awk '
    function trim(s) { gsub(/^[[:space:]]+|[[:space:]]+$/, "", s); return s }
    function scalar(v,   q, i) {
      v = trim(v); q = substr(v, 1, 1)
      if (q == "\"" || q == "\047") {
        i = index(substr(v, 2), q)
        return i ? substr(v, 2, i - 1) : substr(v, 2)
      }
      sub(/[[:space:]]+#.*$/, "", v)
      return trim(v)
    }
    function inline_items(s,   i, c, q, cur, v) {
      q = ""; cur = ""
      for (i = 1; i <= length(s); i++) {
        c = substr(s, i, 1)
        if (q != "") { if (c == q) q = ""; cur = cur c; continue }
        if (c == "\"" || c == "\047") { q = c; cur = cur c; continue }
        if (c == "," || c == "]") {
          v = scalar(cur); if (v != "") print v
          cur = ""
          if (c == "]") return
          continue
        }
        cur = cur c
      }
      v = scalar(cur); if (v != "") print v
    }
    { sub(/\r$/, "") }
    NR == 1 { if ($0 != "---") exit; next }
    $0 == "---" { exit }
    /^paths:[[:space:]]*\[/ { line = $0; sub(/^paths:[[:space:]]*\[/, "", line); inline_items(line); next }
    /^paths:/ { inpaths = 1; next }
    inpaths && /^[[:space:]]*-[[:space:]]/ {
      line = $0; sub(/^[[:space:]]*-[[:space:]]*/, "", line)
      v = scalar(line); if (v != "") print v
      next
    }
    inpaths && /^[[:space:]]*(#|$)/ { next }
    inpaths && !/^[[:space:]]/ { inpaths = 0 }
  ' "$1"
}

# frontmatter 를 뺀 본문
claude_rule_body() {
  awk '{ sub(/\r$/, "") } NR == 1 && $0 == "---" { fm = 1; next } fm && $0 == "---" { fm = 0; next } !fm { print }' "$1"
}

# frontmatter 의 한 줄짜리 값을 YAML 스칼라 규칙대로 읽는다($1=파일, $2=키). 없으면 빈 출력.
claude_fm_value() {
  awk -v key="$2" '
    function trim(s) { gsub(/^[[:space:]]+|[[:space:]]+$/, "", s); return s }
    function scalar(v,   q, i, c, out) {
      v = trim(v); q = substr(v, 1, 1)
      if (q == "\"") {
        out = ""
        for (i = 2; i <= length(v); i++) {
          c = substr(v, i, 1)
          if (c == "\\") { i++; out = out substr(v, i, 1); continue }
          if (c == "\"") break
          out = out c
        }
        return out
      }
      if (q == "\047") {
        out = ""
        for (i = 2; i <= length(v); i++) {
          c = substr(v, i, 1)
          if (c == "\047") {
            if (substr(v, i + 1, 1) == "\047") { out = out c; i++; continue }
            break
          }
          out = out c
        }
        return out
      }
      sub(/[[:space:]]+#.*$/, "", v)
      return trim(v)
    }
    { sub(/\r$/, "") }
    NR == 1 { if ($0 != "---") exit; next }
    $0 == "---" { exit }
    index($0, key ":") == 1 { print scalar(substr($0, length(key) + 2)); exit }
  ' "$1"
}

# --- 이슈 #65: 훅 어댑터. 원본은 Claude 형식(.claude/settings.json 의 hooks + .claude/hooks/*)이고,
#     .claude/hooks/hook-adapter.py 가 Codex(.codex/hooks.json)·agy(.agents/hooks.json) 설정을 생성한다.
emit_hooks() {
  local target="$1" dst
  case "$target" in
    codex) dst="$TARGET/.codex/hooks.json" ;;
    agy) dst="$TARGET/.agents/hooks.json" ;;
    *) return 0 ;;
  esac
  [ -f "$TARGET/.claude/settings.json" ] && [ -f "$TARGET/.claude/hooks/hook-adapter.py" ] || return 0
  if ! command -v python3 >/dev/null 2>&1; then
    echo "Warning: python3 not found — $target hook adapter (${dst#"$TARGET/"}) not generated." >&2
    return 0
  fi
  if [ -f "$dst" ] && ! grep -qE "hook-adapter\.py|personal-gate\.sh" "$dst"; then
    echo "Warning: ${dst#"$TARGET/"} was not generated by agents-scaffold — left untouched." >&2
    return 0
  fi
  mkdir -p "$(dirname "$dst")"
  if python3 "$TARGET/.claude/hooks/hook-adapter.py" emit "$target" "$TARGET/.claude/settings.json" > "$dst.tmp"; then
    mv "$dst.tmp" "$dst"
    echo "== $target hooks generated at ${dst#"$TARGET/"} from .claude/settings.json ==" >&2
  else
    rm -f "$dst.tmp"
    echo "Warning: could not generate ${dst#"$TARGET/"} from .claude/settings.json." >&2
  fi
}
